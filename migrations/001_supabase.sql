-- Run once in Supabase SQL Editor, or use: python server.py init-db
-- Application tables are outside public and not exposed by the Data API.
CREATE SCHEMA IF NOT EXISTS anredseller;
REVOKE ALL ON SCHEMA anredseller FROM PUBLIC;
SET LOCAL search_path TO anredseller, pg_catalog;
CREATE TABLE IF NOT EXISTS metadata (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS owners (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS products (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, document TEXT NOT NULL, published SMALLINT NOT NULL DEFAULT 0 CHECK (published IN (0,1)), updated_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS customers (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL, nama TEXT NOT NULL, nohp TEXT NOT NULL, created_at BIGINT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS customers_email_ci ON customers(lower(email));
CREATE TABLE IF NOT EXISTS orders (id TEXT PRIMARY KEY, document TEXT NOT NULL, status TEXT NOT NULL, idempotency_key TEXT UNIQUE NOT NULL, created_at BIGINT NOT NULL, customer_id BIGINT REFERENCES customers(id));
CREATE TABLE IF NOT EXISTS login_attempts (address TEXT NOT NULL, attempted_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS owner_sessions (token TEXT PRIMARY KEY, owner_id BIGINT NOT NULL REFERENCES owners(id), expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS customer_sessions (token TEXT PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE, expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS customer_addresses (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE, document TEXT NOT NULL, is_default SMALLINT NOT NULL DEFAULT 0 CHECK (is_default IN (0,1)));
CREATE UNIQUE INDEX IF NOT EXISTS customer_default_address ON customer_addresses(customer_id) WHERE is_default=1;
CREATE TABLE IF NOT EXISTS customer_state (customer_id BIGINT PRIMARY KEY REFERENCES customers(id) ON DELETE CASCADE, document TEXT NOT NULL, revision BIGINT NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS customer_order_history ON orders(customer_id,created_at);
ALTER TABLE metadata ENABLE ROW LEVEL SECURITY;
ALTER TABLE owners ENABLE ROW LEVEL SECURITY;
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE login_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE owner_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_addresses ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_state ENABLE ROW LEVEL SECURITY;
