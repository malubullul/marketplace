import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const temporary = await mkdtemp(join(tmpdir(), "anredseller-error-page-"));
const check = process.argv.includes("--check");
const shared = {
  absWorkingDir: root,
  bundle: true,
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  tsconfig: "tsconfig.json",
  logLevel: "warning",
};

try {
  const jsPath = join(temporary, "error-page.js");
  const cssPath = join(temporary, "error-page.css");
  const serverPath = join(temporary, "render.cjs");
  await build({ ...shared, entryPoints: ["frontend/error-page/client.tsx"], outfile: jsPath,
    platform: "browser", format: "iife", target: "es2020", legalComments: "linked" });
  await build({ ...shared, entryPoints: ["frontend/error-page/server.tsx"], outfile: serverPath,
    platform: "node", format: "cjs", target: "node22" });
  execFileSync(process.execPath, [join(root, "node_modules/@tailwindcss/cli/dist/index.mjs"),
    "-i", "frontend/styles/error-page.css", "-o", cssPath, "--minify"], { cwd: root, stdio: "inherit" });
  const javascript = await readFile(jsPath);
  const stylesheet = await readFile(cssPath);
  const packages = ["react", "react-dom", "scheduler", "lucide-react", "@radix-ui/react-slot",
    "@radix-ui/react-compose-refs", "class-variance-authority", "clsx", "tailwind-merge", "tailwindcss"];
  let licenses = await readFile(jsPath + ".LEGAL.txt", "utf8");
  for (const name of packages) {
    const filename = name === "clsx" ? "license" : name === "tailwind-merge" ? "LICENSE.md" : "LICENSE";
    licenses += `\n\n--- ${name} ---\n` + await readFile(join(root, "node_modules", name, filename), "utf8");
  }
  const version = createHash("sha256").update(javascript).update(stylesheet).digest("hex").slice(0, 12);
  const { render } = createRequire(import.meta.url)(serverPath);
  const html = `<!doctype html>
<!-- Generated by npm run build:ui. Edit components/ui/oversized-404-numeral.tsx. -->
<html lang="id">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="robots" content="noindex, follow" />
    <title>404 — Halaman tidak ditemukan | Anredseller</title>
    <link rel="stylesheet" href="/css/generated/error-page.css?v=${version}" />
    <script src="/js/generated/error-page.js?v=${version}" defer></script>
  </head>
  <body>
    <main id="error-page">${render()}</main>
  </body>
</html>
`;
  const outputs = new Map([
    ["404.html", Buffer.from(html)],
    ["js/generated/error-page.js", javascript],
    ["js/generated/error-page.js.LEGAL.txt", Buffer.from(licenses)],
    ["css/generated/error-page.css", stylesheet],
  ]);
  for (const [path, contents] of outputs) {
    const destination = join(root, path);
    if (check) {
      const existing = await readFile(destination).catch(() => Buffer.alloc(0));
      if (!contents.equals(existing)) throw new Error(`${path} is stale. Run npm run build:ui and commit the generated files.`);
    } else {
      await mkdir(dirname(destination), { recursive: true });
      await writeFile(destination, contents);
    }
  }
  console.log(check ? "404 build is up to date." : "Built the React 404, Tailwind stylesheet and no-JS HTML fallback.");
} finally {
  await rm(temporary, { recursive: true, force: true });
}
